export function Icon({ n, className = "" }) {
  const svg = ICONS[n];
  if (!svg) {
    // Return a placeholder box so the UI doesn't break for missing icons
    return (
      <span
        className={`inline-flex items-center justify-center rounded bg-slate-200 ${className}`}
        aria-hidden="true"
        title={n}
      />
    );
  }
  return (
    <span className={`inline-flex items-center justify-center shrink-0 ${className}`} aria-hidden="true">
      {svg}
    </span>
  );
}

/* ─── MiniSparkline ───────────────────────────────────────────── */
export function MiniSparkline({ data = [], color = "#2563EB", width = 80, height = 32 }) {
  if (!data || data.length < 2) return null;
  const min = Math.min(...data);
  const max = Math.max(...data);
  const range = max - min || 1;
  const step = width / (data.length - 1);
  const points = data
    .map((v, i) => {
      const x = i * step;
      const y = height - ((v - min) / range) * (height - 4) - 2;
      return `${x},${y}`;
    })
    .join(" ");

  return (
    <svg width={width} height={height} aria-hidden="true">
      <polyline
        points={points}
        className="mini-line"
        stroke={color}
        fill="none"
        strokeWidth="2.5"
        strokeLinecap="round"
        strokeLinejoin="round"
      />
    </svg>
  );
}

/* ─── Modal ───────────────────────────────────────────────────── */
export function Modal({ open, onClose, title, children }) {
  if (!open) return null;
  return (
    <div
      className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-slate-900/50 backdrop-blur-sm animate-fadeIn"
      role="dialog"
      aria-modal="true"
      aria-labelledby="modal-title"
      onClick={(e) => { if (e.target === e.currentTarget) onClose(); }}
    >
      <div className="w-full max-w-md rounded-2xl bg-white shadow-2xl animate-scaleIn">
        <div className="flex items-center justify-between px-6 py-5 border-b border-slate-100">
          <h2 id="modal-title" className="text-base font-bold text-navy">{title}</h2>
          <button
            onClick={onClose}
            className="rounded-lg p-1.5 text-slate-400 hover:bg-slate-100 transition"
            aria-label="Close modal"
          >
            <Icon n="x" className="h-4 w-4" />
          </button>
        </div>
        <div className="px-6 py-5">{children}</div>
      </div>
    </div>
  );
}